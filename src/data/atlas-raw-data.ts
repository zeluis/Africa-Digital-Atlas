// Generate full unified entity dictionary
export function getInitialEntities(): AtlasEntity[] {
  const baseEntities = [...ATLAS_ENTITIES];
  const baseIds = new Set(baseEntities.map(e => e.id));

  // Add the remaining sovereign states
  for (const [id, data] of Object.entries(ALL_ENTITIES_DATA)) {
    if (!baseIds.has(id)) {
      baseEntities.push({
        id,
        iso2: data.iso2 || id.substring(0, 2),
        name: data.name || id,
        officialName: data.officialName || data.name || id,
        type: 'country',
        sovereign: true,
        region: data.region || 'Western Africa',
        capital: data.capital || 'Capital',
        coordinates: { lat: 0, lng: 20 },
        landAreaKm2: data.landAreaKm2 || 100000,
        currency: data.currency || { code: 'USD', name: 'US Dollar', symbol: '$' },
        languages: data.languages || { official: ['French'] },
        governmentType: data.governmentType || 'Republic',
        landlocked: data.geographicType === 'Landlocked',
        geographicType: data.geographicType || 'Coastal',
        incomeLevel: data.incomeLevel || 'Low income',
        blocs: data.blocs || ['AU', 'AfCFTA'],
        facts: {
          callingCode: '+000',
          largestCity: data.capital || 'Capital',
          mainExports: ['Agricultural goods', 'Minerals']
        },
        summary: data.summary || `${data.name} is a sovereign state in ${data.region}.`
      });
    }
  }

  return baseEntities;
}

