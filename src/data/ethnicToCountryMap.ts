export function getAuthoritativeCountryForEthnic(identifier: string): string | null {
  if (!identifier) return null;
  const clean = identifier.trim().toLowerCase();
  if (AUTHENTIC_ETHNIC_TO_COUNTRY_MAP[clean]) {
    return AUTHENTIC_ETHNIC_TO_COUNTRY_MAP[clean];
  }
  
  // Try removing sub-branch suffixes like -n, -c, -e, -s, -w, numbers
  const baseSlug = clean
    .replace(/-(?:[ncesw]|\d+)$/i, "")
    .replace(/\s+[ncesw]$/i, "")
    .replace(/\s+\d+$/i, "")
    .trim();
    
  if (AUTHENTIC_ETHNIC_TO_COUNTRY_MAP[baseSlug]) {
    return AUTHENTIC_ETHNIC_TO_COUNTRY_MAP[baseSlug];
  }

  // Try extracting the first token before hyphen
  const firstToken = clean.split("-")[0];
  if (firstToken && AUTHENTIC_ETHNIC_TO_COUNTRY_MAP[firstToken]) {
    return AUTHENTIC_ETHNIC_TO_COUNTRY_MAP[firstToken];
  }

  return null;
}
